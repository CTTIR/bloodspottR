test_that("custom grouping and saved-result refresh preserve usable prior data", {
  skip_if_not_installed("shiny")
  x <- bs_example(); x$slides$site <- rep(c("Brain", "Skin", "Heart", "Tumor"), 2)
  path <- tempfile(fileext = ".json"); on.exit(unlink(path))
  save <- function(x) jsonlite::write_json(unclass(x), path, auto_unbox = TRUE, dataframe = "rows", na = "null")
  save(x)
  expect_s3_class(bs_app(path, launch = FALSE, group_by = "site", group_label = "Sample", title = "Collection"), "shiny.appobj")
  expect_error(bs_app(x, launch = FALSE, group_by = "absent"), "group_by")
  shiny::testServer(.bs_app_server(.bs_app_results(x), result_path = path, group_by = "site"), {
    session$setInputs(organ = "Brain", qc = "", search = "", refresh_slide = 0)
    expect_equal(nrow(filtered()), 2)
    y <- x; y$slides$red_area_mm2[1] <- .7; save(y)
    session$setInputs(refresh_slide = 1)
    expect_equal(current()$slides$red_area_mm2[1], .7)
    writeLines("broken", path)
    session$setInputs(refresh_slide = 2)
    expect_match(output$viewer_status, "previous measurements retained")
    expect_equal(current()$slides$red_area_mm2[1], .7)
    save(x); session$setInputs(live_refresh = TRUE)
    session$elapse(2100)
    expect_equal(current()$slides$red_area_mm2[1], 0)
    session$setInputs(live_refresh = FALSE)
    upload <- tempfile(fileext = ".csv")
    write.csv(x$slides, upload, row.names = FALSE)
    session$setInputs(upload = data.frame(name = "valid.csv", datapath = upload))
    expect_match(output$status, "Imported")
    expect_null(watched_path())
    write.csv(bs_example()$slides, upload, row.names = FALSE)
    session$setInputs(upload = data.frame(name = "missing-group.csv", datapath = upload))
    expect_match(output$status, "Missing grouping column")
    session$setInputs(demo = 1)
    expect_true("site" %in% names(current()$slides))
    unlink(upload)
  })
})

test_that("native subprocess errors and argument transport have bounded behavior", {
  skip_if_not_installed("processx")
  expect_error(.bs_slide_python("", c("info", "missing.svs")), "slide_python")
  calls <- list()
  local_mocked_bindings(run = function(command, args, ...) {
    calls[[length(calls) + 1L]] <<- list(command = command, args = args, settings = list(...))
    if (command == "bad") return(list(status = 1L, stderr = "reader error"))
    list(status = 0L, stdout = '{"width":1}', stderr = "")
  }, .package = "processx")
  expect_match(.bs_slide_python("python", c("info", "a path.svs")), "width")
  expect_equal(tail(calls[[1]]$args, 2), c("info", "a path.svs"))
  expect_equal(calls[[1]]$settings$timeout, 30)
  expect_true(calls[[1]]$settings$cleanup_tree)
  expect_error(.bs_slide_python("bad", c("info", "x")), "reader error")
})

test_that("upload request limits are scoped to the running application", {
  skip_if_not_installed("shiny")
  old <- getOption("shiny.maxRequestSize"); on.exit(options(shiny.maxRequestSize = old))
  cleanup <- NULL
  local_mocked_bindings(onStop = function(fun, ...) { cleanup <<- fun }, .package = "shiny")
  options(shiny.maxRequestSize = 1024)
  .bs_app_start()
  expect_equal(getOption("shiny.maxRequestSize"), 20 * 1024^2)
  cleanup()
  expect_equal(getOption("shiny.maxRequestSize"), 1024)
  options(shiny.maxRequestSize = 30 * 1024^2)
  .bs_app_start()
  expect_equal(getOption("shiny.maxRequestSize"), 30 * 1024^2)
  options(shiny.maxRequestSize = 40 * 1024^2)
  cleanup()
  expect_equal(getOption("shiny.maxRequestSize"), 40 * 1024^2)
})

test_that("annotation properties become readable values without discarding metadata", {
  p <- list(classification = list(name = "Tumor"),
    measurements = list(list(name = "Area", value = 12), list(name = "Score", value = NA_real_)),
    notes = "<script>", extra = list(a = 1), missing = NULL)
  table <- .bs_annotation_values(p)
  expect_equal(table$Value[table$Measurement == "Class"], "Tumor")
  expect_equal(table$Value[table$Measurement == "Area"], "12")
  expect_equal(table$Value[table$Measurement == "Score"], "Missing")
  expect_equal(table$Value[table$Measurement == "notes"], "<script>")
  expect_equal(.bs_annotation_values(list())$Value, "None supplied")
  expect_equal(.bs_annotation_values(list(measurements = list(area = 42)))$Value, "42")
  expect_equal(.bs_annotation_values(list(measurements = list(2)))$Value, "2")
})
